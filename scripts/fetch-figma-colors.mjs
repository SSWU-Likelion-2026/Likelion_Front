// Figma Styles(색상)를 읽어와 src/styles/colors.css에 CSS 변수로 저장한다.
// 실행 전: 터미널에서 FIGMA_TOKEN, FIGMA_FILE_KEY 환경변수를 직접 설정할 것.
// 예) $env:FIGMA_TOKEN="..."; $env:FIGMA_FILE_KEY="SEn5vGMB7vontn8qmKCswa"; node scripts/fetch-figma-colors.mjs

import { writeFile, mkdir } from "node:fs/promises";

const TOKEN = process.env.FIGMA_TOKEN;
const FILE_KEY = process.env.FIGMA_FILE_KEY;
const OUT_PATH = "src/styles/colors.css";

if (!TOKEN || !FILE_KEY) {
  console.error("FIGMA_TOKEN, FIGMA_FILE_KEY 환경변수를 먼저 설정하세요.");
  process.exit(1);
}

function toHex({ r, g, b, a }) {
  const c = (v) => Math.round(v * 255).toString(16).padStart(2, "0");
  const hex = `#${c(r)}${c(g)}${c(b)}`;
  return a < 1 ? `${hex}${c(a)}` : hex;
}

function toCssVarName(name) {
  return name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function figmaFetch(path) {
  const res = await fetch(`https://api.figma.com/v1${path}`, {
    headers: { "X-Figma-Token": TOKEN },
  });
  if (!res.ok) {
    throw new Error(`Figma API 오류 (${res.status}): ${await res.text()}`);
  }
  return res.json();
}

const { meta } = await figmaFetch(`/files/${FILE_KEY}/styles`);
const colorStyles = meta.styles.filter((s) => s.style_type === "FILL");

if (colorStyles.length === 0) {
  console.error("색상(FILL) 스타일을 찾지 못했습니다.");
  process.exit(1);
}

const idChunks = [];
const ids = colorStyles.map((s) => s.node_id);
for (let i = 0; i < ids.length; i += 50) idChunks.push(ids.slice(i, i + 50));

const nodesById = {};
for (const chunk of idChunks) {
  const data = await figmaFetch(`/files/${FILE_KEY}/nodes?ids=${chunk.join(",")}`);
  Object.assign(nodesById, data.nodes);
}

const entries = [];
for (const style of colorStyles) {
  const node = nodesById[style.node_id]?.document;
  const fill = node?.fills?.find((f) => f.type === "SOLID");
  if (!fill) continue;
  entries.push({ varName: toCssVarName(style.name), hex: toHex({ ...fill.color, a: fill.opacity ?? 1 }) });
}

const css = [
  "/* auto-generated by scripts/fetch-figma-colors.mjs — 직접 수정하지 말 것 */",
  ":root {",
  ...entries.map((e) => `  --color-${e.varName}: ${e.hex};`),
  "}",
  "",
].join("\n");

await mkdir("src/styles", { recursive: true });
await writeFile(OUT_PATH, css, "utf-8");

console.log(`${entries.length}개 색상 토큰을 ${OUT_PATH}에 저장했습니다.`);
